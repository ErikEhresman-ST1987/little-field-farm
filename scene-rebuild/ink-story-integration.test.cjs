'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const farmSource=fs.readFileSync(require('node:path').join(__dirname,'main.js'),'utf8');
assert.match(farmSource,/const KEY = 'little-field-farm-ink-recovery-test-v1'/,'Recovery branch must isolate test saves');
assert.doesNotMatch(farmSource,/const KEY = 'little-field-farm-scene-rebuild-v4'/,'Recovery branch must not use live save key');
assert.match(farmSource,/function completeStoryObjective\(/,'Farm must use transactional story objective handling');
assert.match(farmSource,/if\(completeStoryObjective\(engine,story.id,objective\)\)openInkStory\(story\)/,'Story completion must verify objective success');
const html=fs.readFileSync(require('node:path').join(__dirname,'index.html'),'utf8');
const bundlePos=html.indexOf('src="story-ink-bundle.js?v=');
const registryPos=html.indexOf('src="story-ink-registry.js?v=');
const unlocksPos=html.indexOf('src="story-unlocks.js?v=');
const mainPos=html.indexOf('src="main.js?v=');
assert.ok(bundlePos>=0&&bundlePos<registryPos&&registryPos<unlocksPos&&unlocksPos<mainPos,'Story dependencies must load in order');
assert.doesNotMatch(html,/story-ink-bundle\.js\?v=20261105-savefix-3/,'Browser must not reuse obsolete Ink bundle');
const bundle=fs.readFileSync(require('node:path').join(__dirname,'story-ink-bundle.js'),'utf8');
const context={window:{},console,structuredClone};
vm.runInNewContext(bundle,context);
const factory=context.window.FarmInk?.createCoordinator;
assert.equal(typeof factory,'function','Ink coordinator must load in browser context');
const engine=factory();
const story='juliette';
assert.equal(engine.view(story).invitation,'available');
engine.decide(story,'accept');
assert.equal(engine.view(story).invitation,'active');
assert.equal(engine.view(story).choices.length,2);
engine.choose(story,1);
assert.match(engine.view(story).lines.join(' '),/wheat for bread/);
assert.equal(engine.event(story,'chapter.advance').changed,false,'Cannot skip chapter with wrong event');
assert.equal(engine.event(story,'wheat.delivered').completed,true);
assert.equal(engine.event(story,'wheat.delivered').changed,false,'Cannot repeat delivery');
assert.equal(engine.manager.registry.get(story).chapterReady,true);
const restored=factory(engine.snapshot());
assert.equal(restored.manager.registry.get(story).chapterReady,true,'Restore pending next chapter');
restored.nextChapter(story);
assert.equal(restored.view(story).chapter,'chapter-2');
assert.equal(restored.view(story).choices.length,2);
restored.choose(story,0);
assert.equal(restored.event(story,'chapter.advance').completed,true);
restored.nextChapter(story);
assert.equal(restored.view(story).chapter,'chapter-3');
assert.equal(restored.view(story).choices.length,0);
assert.equal(restored.event(story,'finish.story').completed,true);
assert.equal(restored.view(story).invitation,'completed');
const done=factory(restored.snapshot());
assert.equal(done.view(story).invitation,'completed','Completed story survives reload');
console.log('Ink story integration: PASS');
